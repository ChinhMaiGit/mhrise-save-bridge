"""Regenerate src/mhrise_save_bridge/_curves.py from a clone of ChevalGrand/mhrise-save-editor.

usage: python tools/gen_curves.py <path to citrus.rs> <output .py>
"""

import re
import sys

from pathlib import Path

ROW_PATTERN = (
    r'index: (\d+),\s*p: hex!\("(\w+)"\),\s*a: hex!\("(\w+)"\),'
    r'\s*b: hex!\("(\w+)"\),\s*gx: hex!\("(\w+)"\),\s*gy: hex!\("(\w+)"\)'
)


def main():
    source = Path(sys.argv[1]).read_text(encoding = "utf-8")
    rows = re.findall(ROW_PATTERN, source)
    assert [int(row[0]) for row in rows] == list(range(128))
    lines = [
        '"""The 128 elliptic-curve presets of the Citrus cipher (generated by tools/gen_curves.py).',
        "",
        "Source: ChevalGrand/mhrise-save-editor, src/crypto/citrus.rs (MIT, (c) 2026 ChevalGrand).",
        "Each row is p, a, b, gx, gy as little-endian hex strings, in the order of the source table.",
        '"""',
        "",
        "CURVE_ROWS = (",
    ]
    for row in rows:
        lines.append("    (")
        lines.extend(f'        "{value}",' for value in row[1:])
        lines.append("    ),")
    lines.append(")")
    Path(sys.argv[2]).write_text("\n".join(lines) + "\n", encoding = "utf-8")


if __name__ == "__main__":
    main()
